def test_circular_orbit_closes(circular_state, tight) -> None:
    """A point-mass circular orbit returns to its initial state in one period."""
    field = PointMassField(mu=MU_MOON)
    r0 = float(np.linalg.norm(circular_state[:3]))
    period = 2.0 * np.pi * np.sqrt(r0**3 / MU_MOON)
    t_eval = np.array([0.0, period])

    arc = propagate(field, circular_state, t_eval, 0, tight)

    assert not arc.carries_stm
    # rtol=0 on purpose: the default 1e-5 would be relative to a 1.8e6 m
    # radius, i.e. an 18 m tolerance, and the test would pass on a broken
    # propagator.
    assert np.allclose(arc.r[-1], circular_state[:3], rtol=0.0, atol=1e-3)
    assert np.allclose(arc.v[-1], circular_state[3:], rtol=0.0, atol=1e-6)


def test_stm_starts_at_identity(circular_state, tight) -> None:
    field = PointMassField(mu=MU_MOON)
    arc = propagate(field, circular_state, np.array([0.0, 60.0, 120.0]), 0,
                    tight, GradientConfig())
    assert arc.carries_stm
    assert np.allclose(arc.stm[0], np.eye(6), rtol=0.0, atol=1e-12)


def test_stm_matches_finite_difference_of_flow(circular_state, tight) -> None:
    """:math:`\\Phi` is the Jacobian of the flow. Verify it as one.

    Six perturbed propagations, differenced against six more, give the
    columns of :math:`\\partial\\mathbf x(t)/\\partial\\mathbf x(t_0)`
    directly.  A transposed or mis-blocked variational term fails here and
    passes every structural check, which is why this test exists.

    The :math:`J_2` field is used rather than a point mass so that the
    position--position block is not degenerate.
    """
    field = J2Field(mu=MU_MOON, reference_radius=R_MOON, j2=J2_MOON)
    span = 1800.0
    t_eval = np.array([0.0, span])
    # Symmetric perturbations: metres in position, mm/s in velocity, both
    # far above roundoff and far below the scale on which the flow curves.
    steps = np.array([1.0, 1.0, 1.0, 1.0e-3, 1.0e-3, 1.0e-3])

    arc = propagate(field, circular_state, t_eval, 2, tight, GradientConfig())
    phi_integrated = arc.stm[-1]

    phi_numeric = np.empty((6, 6))
    for j in range(6):
        bump = np.zeros(6)
        bump[j] = steps[j]
        plus = propagate(field, circular_state + bump, t_eval, 2, tight)
        minus = propagate(field, circular_state - bump, t_eval, 2, tight)
        end_plus = np.concatenate([plus.r[-1], plus.v[-1]])
        end_minus = np.concatenate([minus.r[-1], minus.v[-1]])
        phi_numeric[:, j] = (end_plus - end_minus) / (2.0 * steps[j])

    # Compare column by column: the columns have wildly different magnitudes
    # (a velocity column carries seconds), so a single absolute tolerance
    # would be vacuous for some and impossible for others.
    for j in range(6):
        scale = np.max(np.abs(phi_numeric[:, j]))
        assert np.allclose(phi_integrated[:, j], phi_numeric[:, j],
                           rtol=1e-6, atol=1e-8 * scale), f"column {j}"


def test_stm_stays_symplectic_over_an_orbit(circular_state, tight) -> None:
    """The integration diagnostic the campaign records once per arc."""
    field = J2Field(mu=MU_MOON, reference_radius=R_MOON, j2=J2_MOON)
    r0 = float(np.linalg.norm(circular_state[:3]))
    period = 2.0 * np.pi * np.sqrt(r0**3 / MU_MOON)
    t_eval = np.linspace(0.0, period, 25)

    arc = propagate(field, circular_state, t_eval, 2, tight, GradientConfig())
    speed0 = float(np.linalg.norm(circular_state[3:]))
    defect = symplectic_defect(arc.stm, r0, r0 / speed0)

    assert defect.shape == (25,)
    assert float(np.max(defect)) < 1.0e-9


def test_gradient_degree_is_recorded(circular_state, tight) -> None:
    """The resolved gradient degree must be recorded, not left as ``None``.

    Q13 -- which gradient degree the benchmark STM is built at -- turns on
    this number being auditable after the fact.
    """
    field = J2Field(mu=MU_MOON, reference_radius=R_MOON, j2=J2_MOON)
    t_eval = np.array([0.0, 60.0])

    matched = propagate(field, circular_state, t_eval, 2, tight,
                        GradientConfig(degree=None))
    explicit = propagate(field, circular_state, t_eval, 2, tight,
                         GradientConfig(degree=1))

    assert matched.gradient_degree == 2
    assert explicit.gradient_degree == 1
    assert propagate(field, circular_state, t_eval, 2,
                     tight).gradient_degree is None


def test_realized_rhs_count_is_reported(circular_state, tight) -> None:
    """Budget accounting needs realized work, not a nominal per-call figure."""
    field = PointMassField(mu=MU_MOON)
    arc = propagate(field, circular_state, np.linspace(0.0, 600.0, 6), 0, tight)
    assert arc.n_rhs > 0


