"""Verification of the reference propagation and the state-transition matrix.

The load-bearing test is :func:`test_stm_matches_finite_difference_of_flow`.
Every later result in the campaign is generated by :math:`\\Phi`, and the only
way to know the variational block is right is to compare it against what it
claims to be -- the derivative of the flow with respect to the initial state.
Symplecticity is necessary but not sufficient: a variational block with a
transposed gradient would still be symplectic and still be wrong.

All fixtures use the analytic fields of :mod:`tda.analytic`, so the suite runs
without the spherical-harmonic kernel installed.
"""

from __future__ import annotations

import numpy as np
import pytest

from conftest import J2_MOON, MU_MOON, R_MOON
from tda.analytic import J2Field, PointMassField
from tda.config import GradientConfig
from tda.dynamics import (
    IntegrationError,
    estimate_rhs_work_factor,
    estimate_syntheses_per_rhs,
    propagate,
    propagate_schedule,
)
from tda.stm import symplectic_defect

# ---------------------------------------------------------------------------
# The analytic gradient
# ---------------------------------------------------------------------------


def test_point_mass_gradient_is_symmetric_and_traceless() -> None:
    """Laplace's equation in free space: the Hessian of ``1/r`` is traceless."""
    field = PointMassField(mu=MU_MOON)
    r = np.array([1.8e6, 3.0e5, -7.0e5])
    g = field.exact_gradient(r)
    assert np.array_equal(g, g.T), "an outer product is exactly symmetric"
    assert abs(np.trace(g)) < 1e-12 * abs(g[0, 0])


def test_finite_difference_gradient_matches_the_closed_form() -> None:
    """Prices the central-difference estimator against a known answer.

    This is the check that licenses using a differenced gradient on the real
    field, where no closed form is available.
    """
    from tda.field import gravity_gradient

    field = PointMassField(mu=MU_MOON)
    r = np.array([1.8e6, 3.0e5, -7.0e5])
    numeric = gravity_gradient(field, r, 0.0, 0, GradientConfig(step_m=1.0))
    exact = field.exact_gradient(r)
    # A central difference truncates at O(h^2 a'''), which at these radii is
    # ~1e-7 relative; the tolerance states that rather than pinning digits the
    # estimator does not have.
    assert np.allclose(numeric, exact, rtol=1e-6,
                       atol=1e-9 * float(np.max(np.abs(exact))))


